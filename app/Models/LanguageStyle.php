<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\Cache;

/**
 * @property int $id
 * @property string $name
 * @property string $slug
 * @property string $icon
 * @property string $color
 * @property string|null $instructions
 * @property array<int, array{original: string, styled: string}> $examples
 * @property list<string> $content_types
 * @property string $sensitive_policy
 * @property bool $is_humorous
 * @property bool $is_random
 * @property bool $is_original
 * @property bool $is_active
 * @property int $version
 */
class LanguageStyle extends Model
{
    public const COLORS = [
        'mustard' => 'bg-mustard text-charcoal',
        'forest' => 'bg-forest text-mustard',
        'terra' => 'bg-terra text-cream',
        'charcoal' => 'bg-charcoal text-mustard',
        'cream' => 'bg-mustard-100 text-terra-ink',
        'rust' => 'bg-terra-ink text-cream',
        'plain' => 'bg-surface-2 text-ink',
    ];

    protected $fillable = ['name', 'description', 'icon', 'color', 'instructions', 'examples', 'content_types', 'sensitive_policy', 'is_humorous', 'is_active', 'sort_order'];

    protected function casts(): array
    {
        return [
            'examples' => 'array',
            'content_types' => 'array',
            'is_humorous' => 'boolean',
            'is_random' => 'boolean',
            'is_original' => 'boolean',
            'is_active' => 'boolean',
        ];
    }

    /** @return HasMany<LanguageStyleVersion, $this> */
    public function versions(): HasMany
    {
        return $this->hasMany(LanguageStyleVersion::class)->orderByDesc('version');
    }

    /** @return Collection<int, LanguageStyle> */
    public static function active(): Collection
    {
        // Cache raw attributes, not objects (Laravel 13 cache.serializable_classes = false).
        return static::hydrate(Cache::remember('mtc:styles:active:attrs', 600, fn () => static::where('is_active', true)->orderBy('sort_order')->get()->map(fn (self $m) => $m->getAttributes())->all()));
    }

    public static function flush(): void
    {
        Cache::forget('mtc:styles:active:attrs');
    }

    protected static function booted(): void
    {
        static::saved(fn () => static::flush());
        static::deleted(fn () => static::flush());
    }

    /** Can this style be generated by AI (not "Originál", not the random picker)? */
    public function isGeneratable(): bool
    {
        return ! $this->is_original && ! $this->is_random;
    }

    public function allowsSensitive(): bool
    {
        return $this->sensitive_policy === 'allowed' || ! $this->is_humorous;
    }

    public function supports(string $contentType): bool
    {
        return in_array($contentType, (array) $this->content_types, true);
    }

    public function badgeClass(): string
    {
        return self::COLORS[$this->color] ?? self::COLORS['mustard'];
    }
}
